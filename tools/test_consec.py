import socket
import struct

s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
s.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
s.settimeout(5.0)
s.connect(("192.168.4.1", 3240))

def xfer(req):
    s.sendall(bytes(req))
    resp = s.recv(2048)
    return resp

xfer([0x02, 0x01])
xfer(bytes([0x11]) + struct.pack("<I", 2500000))
xfer([0x04, 0x00, 0x32, 0x00, 0x00, 0x00])

xfer([0x12, 56, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
xfer([0x12, 16, 0x9E, 0xE7])
xfer([0x12, 56, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
xfer([0x12, 8, 0x00])

xfer([0x05, 0x00, 0x01, 0x02])
xfer([0x05, 0x00, 0x01, 0x04, 0x00, 0x00, 0x00, 0x50])
xfer([0x05, 0x00, 0x01, 0x08, 0x00, 0x00, 0x00, 0x00])
xfer([0x05, 0x00, 0x01, 0x01, 0x52, 0x00, 0x00, 0x23])

# Set TAR to 0xE000ED00, then read 4 consecutive DRWs in one DAP_Transfer
req = [0x05, 0x00, 5, 0x05, 0x00, 0xED, 0x00, 0xE0, 0x0F, 0x0F, 0x0F, 0x0F]
resp = xfer(req)
print(f"Resp len: {len(resp)}, raw: {[hex(b) for b in resp]}")
if len(resp) >= 19:
    words = struct.unpack("<4I", resp[3:19])
    print("Words:", [f"0x{w:08X}" for w in words])

s.close()
