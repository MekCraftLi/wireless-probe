import socket
import struct

s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
s.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
s.settimeout(5.0)
s.connect(("192.168.4.1", 3240))

def xfer(req):
    s.sendall(bytes(req))
    return s.recv(2048)

xfer([0x02, 0x01])
xfer(bytes([0x11]) + struct.pack("<I", 2500000))
xfer([0x04, 0x00, 0x32, 0x00, 0x00, 0x00])

xfer([0x12, 56, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
xfer([0x12, 16, 0x9E, 0xE7])
xfer([0x12, 56, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
xfer([0x12, 8, 0x00])

# DPIDR
r = xfer([0x05, 0x00, 0x01, 0x02])
dpidr = struct.unpack("<I", r[3:7])[0] if len(r) >= 7 else 0
print(f"DPIDR: 0x{dpidr:08X}")

# Powerup & AP 0
xfer([0x05, 0x00, 0x01, 0x04, 0x00, 0x00, 0x00, 0x50])
xfer([0x05, 0x00, 0x01, 0x08, 0x00, 0x00, 0x00, 0x00])
xfer([0x05, 0x00, 0x01, 0x01, 0x52, 0x00, 0x00, 0x23])

# Clean 2-transfer read of CPUID (0xE000ED00)
tar_b = list(struct.pack("<I", 0xE000ED00))
resp = xfer([0x05, 0x00, 0x02, 0x05] + tar_b + [0x0F])
print("Clean read resp:", [hex(b) for b in resp])
if len(resp) >= 7:
    val = struct.unpack("<I", resp[3:7])[0]
    print(f"Read CPUID: 0x{val:08X}, Count={resp[1]}, ACK={resp[2]}")

s.close()
